// Bangun relasi dan kalkulasi unit cost sesuai Blueprint Bagian 10.1
rawSeeds.forEach((item, idx) => {
  const prodId = `prod-${idx + 1}`;
  const batchId = `batch-${idx + 1}`;
  const batchPublicId = `batch-${item.publicId.replace("prod-", "")}-today`;

  initialProducts.push({
    id: prodId,
    shopId: "shop-01",
    publicId: item.publicId,
    name: item.name,
    aliases: item.aliases,
    category: item.category,
    saleUnit: item.saleUnit,
    priceIdr: item.priceIdr,
    published: true,
    description: item.description,
    createdAt: "2026-10-13T06:00:00Z",
    updatedAt: "2026-10-13T06:00:00Z",
  });

  const salableQty = item.intakeQty - item.initialDamage;
  const totalBatchCost = item.purchaseCost + item.freightCost;
  const unitCost = salableQty > 0 ? Math.round((totalBatchCost / salableQty) * 100) / 100 : 0;

  initialBatches.push({
    id: batchId,
    productId: prodId,
    supplierId: item.supplierId,
    publicId: batchPublicId,
    receivedAt: "2026-10-13T06:30:00Z",
    harvestDate: "2026-10-12T16:00:00Z", // H-1 sore
    origin: item.origin,
    receivedQty: item.intakeQty,
    initialDamageQty: item.initialDamage,
    salableQty: salableQty,
    purchaseCost: item.purchaseCost,
    freightCost: item.freightCost,
    prepCost: 0,
    unitCost: unitCost,
    status: "ACTIVE",
    notes: `Penerimaan batch ${item.intakeQty} ${item.saleUnit}`,
    createdAt: "2026-10-13T06:30:00Z",
    updatedAt: "2026-10-13T06:30:00Z",
  });

  if (item.claim) {
    initialClaims.push({
      id: `claim-${idx + 1}`,
      batchId: batchId,
      claim: item.claim,
      sourceType: "SELLER_INSPECTION",
      publicationStatus: "PUBLISHED",
      createdAt: "2026-10-13T06:30:00Z",
    });
  }
});

